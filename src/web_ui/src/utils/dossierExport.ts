/**
 * Utility functions for exporting and downloading Topic Dossiers and
 * Executive Contact profiles as sanitized Markdown (.md) or JSON files.
 */
import { BriefingReport, SocialEntity } from "@/types/schemas";

/**
 * Sanitizes a string into a clean, safe filename.
 * E.g., "AWS Bedrock MicroVM Runtime: Sub-second Persistence!" -> "aws_bedrock_microvm_runtime_sub_second_persistence.md"
 */
export function sanitizeFilename(name: string, extension = ".md"): string {
  if (!name || !name.trim()) return `dossier_export${extension}`;
  const slug = name
    .trim()
    .toLowerCase()
    .replace(/['"“”‘’]/g, "")
    .replace(/[^a-z0-9_-]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .substring(0, 64);
  return `${slug || "dossier_export"}${extension}`;
}

/**
 * Initiates a browser download for a text blob (e.g., Markdown or JSON).
 */
export function downloadTextFile(
  content: string,
  filename: string,
  mimeType = "text/markdown;charset=utf-8"
): void {
  if (typeof window === "undefined") return;
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/**
 * Generates a complete, publication-grade Markdown dossier from a BriefingReport.
 */
export function generateTopicMarkdown(topic: BriefingReport): string {
  if (!topic || typeof topic !== "object") return "";
  const parts: string[] = [];

  const title = topic.topic_title || "Autonomous Topic Research Dossier";
  parts.push(`# ${title}\n`);

  const meta: string[] = [];
  if (topic.context_type && typeof topic.context_type === "string") {
    meta.push(`**Domain / Context**: \`${topic.context_type.replace(/_/g, " ").toUpperCase()}\``);
  }
  if (topic.kind && typeof topic.kind === "string") {
    meta.push(`**Kind**: \`${topic.kind.toUpperCase()}\``);
  }
  if (topic.created_at && typeof topic.created_at === "string") {
    const timeClean = topic.created_at.replace("T", " ").substring(0, 19);
    meta.push(`**Synthesized**: ${timeClean} UTC`);
  }
  meta.push(`**Engine**: AWS Bedrock AgentCore Runtime & Multi-Tier Reasoner`);
  parts.push(`> ${meta.join("  \n> ")}\n`);

  if (topic.explanatory_synthesis && typeof topic.explanatory_synthesis === "string") {
    parts.push(`## ⚡ Explanatory Synthesis & Core Thesis\n`);
    parts.push(`${topic.explanatory_synthesis.trim()}\n`);
  }

  if (Array.isArray(topic.executive_summary) && topic.executive_summary.length > 0) {
    parts.push(`## 📌 Executive Summary & Key Insights\n`);
    topic.executive_summary.forEach((item) => {
      const line = typeof item === "string" ? item.trim() : item != null ? String(item) : "";
      if (line) parts.push(`- ${line}`);
    });
    parts.push("");
  }

  if (Array.isArray(topic.action_items) && topic.action_items.length > 0) {
    parts.push(`## ✅ Action Items & Strategic Follow-ups\n`);
    topic.action_items.forEach((act) => {
      const line = typeof act === "string" ? act.trim() : act != null ? String(act) : "";
      if (line) parts.push(`- [ ] ${line}`);
    });
    parts.push("");
  }

  if (Array.isArray(topic.web_sources) && topic.web_sources.length > 0) {
    parts.push(`## 🔗 Corroborating Citations & Web Sources\n`);
    topic.web_sources.forEach((src) => {
      const url = typeof src === "string" ? src : (src as any)?.url || "";
      const label = typeof src === "string" ? src : (src as any)?.title || (src as any)?.url || "Source";
      if (url) parts.push(`- [${label}](${url})`);
    });
    parts.push("");
  }

  if (topic.deep_dive_markdown && typeof topic.deep_dive_markdown === "string" && topic.deep_dive_markdown.trim()) {
    parts.push(`## 🔬 Deep Dive Research & Technical Specification\n`);
    parts.push(`${topic.deep_dive_markdown.trim()}\n`);
  }

  parts.push(`---\n*Generated by EXAMEN Ambient Knowledge & Action Engine on ${new Date().toISOString()}*`);

  return parts.join("\n");
}

/**
 * Generates a complete Markdown dossier from an Executive Social Contact.
 */
export function generateContactMarkdown(contact: SocialEntity): string {
  if (!contact || typeof contact !== "object") return "";
  const parts: string[] = [];
  const name = contact.name || contact.person_name || "Executive Contact";
  parts.push(`# Executive Intelligence Dossier: ${name}\n`);

  const profile = contact.web_profile;
  const disambiguation = profile?.disambiguation_report;

  const meta: string[] = [];
  if (contact.company_or_role) meta.push(`**Role / Organization**: ${contact.company_or_role}`);
  if (contact.contact_info) meta.push(`**Contact Info**: ${contact.contact_info}`);
  if (contact.location_encountered) meta.push(`**Location**: ${contact.location_encountered}`);
  if (contact.timestamp && typeof contact.timestamp === "string") {
    meta.push(`**Encountered**: ${contact.timestamp.split("T")[0]}`);
  }
  if (profile?.confidence_score != null) {
    meta.push(`**AI Match Certainty**: ${(profile.confidence_score * 100).toFixed(0)}%`);
  }
  if (meta.length > 0) {
    parts.push(`> ${meta.join("  \n> ")}\n`);
  }

  // Verified Profiles
  const profiles: string[] = [];
  if (profile?.linkedin_url || disambiguation?.canonical_linkedin_url) {
    const lUrl = profile?.linkedin_url || disambiguation?.canonical_linkedin_url;
    profiles.push(`- **LinkedIn**: [${lUrl}](${lUrl})`);
  }
  if (profile?.github_url || disambiguation?.canonical_github_url) {
    const gUrl = profile?.github_url || disambiguation?.canonical_github_url;
    profiles.push(`- **GitHub**: [${gUrl}](${gUrl})`);
  }
  if (contact.website_url || profile?.website_url) {
    const wUrl = contact.website_url || profile?.website_url;
    profiles.push(`- **Website**: [${wUrl}](${wUrl})`);
  }
  if (profiles.length > 0) {
    parts.push(`## 🌐 Verified External Profiles\n`);
    parts.push(profiles.join("\n") + "\n");
  }

  // Bio summary
  if (profile?.bio_summary || profile?.headline) {
    parts.push(`## 👤 Executive Profile Summary\n`);
    if (profile.headline) parts.push(`**${profile.headline}**\n`);
    if (profile.bio_summary) parts.push(`${profile.bio_summary}\n`);
  }

  // Expertise
  if (Array.isArray(profile?.areas_of_expertise) && profile.areas_of_expertise.length > 0) {
    parts.push(`## 💡 Areas of Expertise\n`);
    parts.push(profile.areas_of_expertise.map((a) => `- \`${a}\``).join("\n") + "\n");
  }

  // Disambiguation
  if (disambiguation) {
    parts.push(`## 🛡️ Anti-Contamination & Disambiguation Audit\n`);
    if (disambiguation.rationale) {
      parts.push(`> ${disambiguation.rationale}\n`);
    }
    if (Array.isArray(disambiguation.clean_combined_facts) && disambiguation.clean_combined_facts.length > 0) {
      parts.push(`### Corroborated Facts`);
      disambiguation.clean_combined_facts.forEach((fact) => {
        parts.push(`- ✓ ${fact}`);
      });
      parts.push("");
    }
  }

  // Bilateral Commitments
  const commitments = Array.isArray(contact.commitments) ? contact.commitments : [];
  if (commitments.length > 0) {
    parts.push(`## 🤝 Bilateral Commitments\n`);
    commitments.forEach((cmt, i) => {
      const isObj = typeof cmt === "object" && cmt !== null;
      const desc = isObj ? cmt.description : String(cmt);
      const debtor = isObj ? cmt.debtor : "user";
      const status = isObj ? cmt.status : "open";
      const debtorLabel = debtor === "user" ? "You Promised" : `${name} Promised`;
      parts.push(`- **[${debtorLabel}]** [${String(status).toUpperCase()}] ${desc}`);
    });
    parts.push("");
  }

  // Topics
  if (Array.isArray(contact.key_topics) && contact.key_topics.length > 0) {
    parts.push(`## 🏷️ Key Discussion Topics\n`);
    parts.push(contact.key_topics.map((t) => `#${typeof t === "string" ? t.replace(/\s+/g, "-") : String(t)}`).join(" ") + "\n");
  }

  parts.push(`---\n*Generated by EXAMEN Ambient Knowledge & Action Engine on ${new Date().toISOString()}*`);
  return parts.join("\n");
}
