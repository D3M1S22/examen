"""Per-user tenancy: who the current request or background task works for, and where their data lives.

Every authenticated user is a *tenant* with a private folder::

    <EXAMEN_DATA_DIR>/users/<user_id>/
        examen.db      # all of the user's EXAMEN data (actions, contacts, events, ledger, ...)
        bee/           # BEE_CONFIG_DIR of the user's bee-cli login (token file, pairing state)

The current tenant is carried by a context variable. Request handlers set it from the session cookie
or the MCP bearer token (src/serving/auth_middleware.py); per-user background tasks (orchestrator,
event engine, backfill) are created inside ``tenant_scope(user_id)`` so asyncio tasks and
``asyncio.to_thread`` calls inherit it. Code that runs with no tenant (CLI scripts, the test suite,
``AUTH_ENABLED=false``) keeps the legacy single-user behaviour: ``SQLITE_DB_PATH`` and the host's
default bee-cli login.

With ``AUTH_ENABLED=true`` the accessors of user data and per-user runtimes resolve the tenant with
``resolve_tenant()``, which raises ``MissingTenant`` instead of falling back to the legacy store or the
host's Bee login: a forgotten ``tenant_scope`` becomes an error, never a write into shared data.

GDPR: erasing a user is deleting one folder (see ``delete_tenant_data``).
"""

from __future__ import annotations

import contextlib
import contextvars
import os
import re
import shutil
from pathlib import Path
from typing import Dict, Iterator, List, Optional

from src.core.config import settings

_current_tenant: contextvars.ContextVar[Optional[str]] = contextvars.ContextVar("examen_tenant", default=None)

_USER_ID_RE = re.compile(r"^usr_[a-f0-9]{16,32}$")


def is_valid_user_id(user_id: Optional[str]) -> bool:
    """User ids are generated by the auth store; anything else never reaches the filesystem."""
    return bool(user_id) and bool(_USER_ID_RE.match(user_id))


class MissingTenant(RuntimeError):
    """User data or a per-user runtime was requested with no tenant while accounts are enabled."""


def get_tenant_id() -> Optional[str]:
    """The user the current code works for, or None in legacy single-user mode."""
    return _current_tenant.get()


def resolve_tenant() -> Optional[str]:
    """The current tenant for code that touches user data; fail-closed when accounts are enabled.

    Returns None (legacy single-user objects) only with ``AUTH_ENABLED=false``.
    """
    tenant = _current_tenant.get()
    if tenant is None and settings.auth_enabled:
        raise MissingTenant(
            "No user in context: run this inside tenant_scope(user_id) "
            "(scripts: EXAMEN_CLI_USER=<email>, see src/core/cli.py)"
        )
    return tenant


@contextlib.contextmanager
def tenant_scope(user_id: Optional[str]) -> Iterator[Optional[str]]:
    """Runs the block (and every task / thread it starts) on behalf of ``user_id``."""
    if user_id is not None and not is_valid_user_id(user_id):
        raise ValueError("Invalid user id")
    token = _current_tenant.set(user_id)
    try:
        yield user_id
    finally:
        _current_tenant.reset(token)


def set_tenant(user_id: Optional[str]) -> contextvars.Token:
    """Low-level setter for ASGI middleware (pair it with ``reset_tenant``)."""
    if user_id is not None and not is_valid_user_id(user_id):
        raise ValueError("Invalid user id")
    return _current_tenant.set(user_id)


def reset_tenant(token: contextvars.Token) -> None:
    _current_tenant.reset(token)


# ---------------------------------------------------------------------------
# Filesystem layout
# ---------------------------------------------------------------------------

def data_root() -> Path:
    return Path(settings.examen_data_dir).expanduser()


def users_root() -> Path:
    return data_root() / "users"


def tenant_dir(user_id: str, create: bool = True) -> Path:
    if not is_valid_user_id(user_id):
        raise ValueError("Invalid user id")
    path = users_root() / user_id
    if create:
        path.mkdir(mode=0o700, parents=True, exist_ok=True)
    return path


def tenant_db_path(user_id: str) -> str:
    return str(tenant_dir(user_id) / "examen.db")


def tenant_bee_dir(user_id: str, create: bool = True) -> Path:
    path = tenant_dir(user_id, create=create) / "bee"
    if create:
        path.mkdir(mode=0o700, parents=True, exist_ok=True)
        with contextlib.suppress(OSError):
            os.chmod(path, 0o700)
    return path


def tenant_has_bee_login(user_id: str) -> bool:
    """True when the user's private bee-cli folder holds a token (``token-<env>`` file store)."""
    bee_dir = tenant_dir(user_id, create=False) / "bee"
    if not bee_dir.is_dir():
        return False
    return any(p.name.startswith("token-") and p.stat().st_size > 0 for p in bee_dir.iterdir() if p.is_file())


def list_tenant_ids() -> List[str]:
    if settings.storage_backend == "dynamo":
        # No per-user folder is guaranteed: the accounts are the tenants
        from src.core.auth import get_auth_store

        return sorted(u.id for u in get_auth_store().list_users())
    root = users_root()
    if not root.is_dir():
        return []
    return sorted(p.name for p in root.iterdir() if p.is_dir() and is_valid_user_id(p.name))


def delete_tenant_data(user_id: str) -> bool:
    """Irreversibly removes the user's data: the DynamoDB partition (``STORAGE_BACKEND=dynamo``) and
    the user's folder (database, bee token, captures)."""
    erased = False
    if settings.storage_backend == "dynamo":
        from src.core.storage.dynamo_store import DynamoContextStore

        store = DynamoContextStore(user_id=user_id)
        erased = bool(store.export_all())
        store.delete_all_data()
    path = tenant_dir(user_id, create=False)
    if not path.exists():
        return erased
    shutil.rmtree(path)
    return True


# ---------------------------------------------------------------------------
# bee-cli isolation
# ---------------------------------------------------------------------------

def bee_subprocess_env(user_id: Optional[str] = None) -> Optional[Dict[str, str]]:
    """Environment for a `bee` subprocess.

    bee-cli keeps its token in the OS keychain under a fixed key (``bee-cli`` / ``token:<env>``) and
    only falls back to ``$BEE_CONFIG_DIR`` when the keychain is unavailable, so two users on one host
    would overwrite each other's login. For a tenant we force the file store and point it at the
    user's private folder. Returns None (inherit the parent environment) in single-user mode.
    """
    uid = user_id if user_id is not None else resolve_tenant()
    if uid is None:
        return None
    env = dict(os.environ)
    env["BEE_CONFIG_DIR"] = str(tenant_bee_dir(uid))
    env["BEE_FORCE_FILE_STORE"] = "1"
    return env
