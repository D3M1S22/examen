#!/usr/bin/env bash
# Installs or updates EXAMEN on the EC2 host (docs/17_aws_deployment_runbook.md §5). Runs as root.
#
#   host.sh install [bundle.tgz]   first boot (cloud-init user data): packages, user, uv, release, .env, service
#   host.sh update  [bundle.tgz]   new release from s3://$EXAMEN_BUCKET/$EXAMEN_BUNDLE_KEY (SSM Run Command)
#
# Releases live in /opt/examen-releases/<id>; /opt/examen is a symlink to the current one, so a failed
# health check rolls back by pointing the link at the previous release. /var/lib/examen keeps the
# .env and the data folder (Bee logins). User data is in DynamoDB.
set -euo pipefail

MODE="${1:-update}"
BUNDLE="${2:-}"
# shellcheck disable=SC1091
source /etc/examen/deploy.env
export AWS_DEFAULT_REGION="$EXAMEN_STACK_REGION"

RELEASES=/opt/examen-releases
CURRENT=/opt/examen
DATA=/var/lib/examen
ENV_FILE="$DATA/examen.env"
HEALTH_URL=http://127.0.0.1:8000/api/health

log() { echo "==> $(date -u +%H:%M:%S) $*"; }
as_examen() { sudo -u examen -H "$@"; }

healthy() {
  for _ in $(seq 1 45); do
    curl -fsS -m 3 "$HEALTH_URL" >/dev/null 2>&1 && return 0
    sleep 2
  done
  return 1
}

param() {
  aws ssm get-parameter --name "$EXAMEN_PARAM_PREFIX/$1" --with-decryption --query Parameter.Value --output text 2>/dev/null || true
}

prepare_host() {
  log "Packages"
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  apt-get install -y -qq rsync ca-certificates curl jq sqlite3 unzip >/dev/null
  id examen >/dev/null 2>&1 || useradd --system --create-home --home-dir "$DATA" --shell /bin/bash examen
  install -d -o examen -g examen -m 700 "$DATA" "$DATA/data"
  install -d -m 755 "$RELEASES"
  if ! command -v uv >/dev/null; then
    log "uv"
    curl -LsSf https://astral.sh/uv/install.sh | env UV_INSTALL_DIR=/usr/local/bin UV_NO_MODIFY_PATH=1 sh
  fi
  (cd "$DATA" && as_examen uv python install 3.12 >/dev/null)
}

write_env() {
  # Generated once; later edits on the host are kept (delete the file to regenerate it)
  [ -f "$ENV_FILE" ] && return 0
  log "Writing $ENV_FILE"
  local admin_email admin_password
  admin_email="$(param bootstrap-admin-email)"
  admin_password="$(param bootstrap-admin-password)"
  umask 077
  cat >"$ENV_FILE" <<EOF
# Generated by deploy/aws/host.sh (docs/17_aws_deployment_runbook.md §4). AWS credentials come from the instance role.
MCP_HOST=0.0.0.0
MCP_PORT=8000
MCP_STREAMABLE_HTTP=true
MCP_ALLOWED_HOSTS=*
AUTH_ENABLED=true
AUTH_ALLOW_SIGNUP=false
AUTH_COOKIE_SECURE=true
AUTO_START_USER_ORCHESTRATORS=true
STORAGE_BACKEND=dynamo
AUTH_STORE_BACKEND=dynamo
OPS_STORE_BACKEND=dynamo
DYNAMO_REGION=$DYNAMO_REGION
DYNAMO_TABLE_PREFIX=$DYNAMO_TABLE_PREFIX
DYNAMO_TENANT_ROLE_ARN=$DYNAMO_TENANT_ROLE_ARN
AWS_REGION=$AWS_REGION
GATEKEEPER_PROVIDER=bedrock
REASONER_PROVIDER=bedrock
BEDROCK_GATEKEEPER_MODEL=$BEDROCK_GATEKEEPER_MODEL
BEDROCK_REASONER_MODEL=$BEDROCK_REASONER_MODEL
BEDROCK_EMBEDDING_MODEL=$BEDROCK_EMBEDDING_MODEL
TOPIC_SIMILARITY_BACKEND=embedding
PIPELINE_MODE=${PIPELINE_MODE:-local}
AGENTCORE_RUNTIME_ARN=${AGENTCORE_RUNTIME_ARN:-}
BEE_STREAM_TRANSPORT=proxy
LOG_LEVEL=INFO
EXAMEN_BOOTSTRAP_ADMIN=$admin_email
EXAMEN_BOOTSTRAP_ADMIN_PASSWORD=$admin_password
EOF
  chown examen:examen "$ENV_FILE"
  chmod 600 "$ENV_FILE"
}

new_release() {
  local bundle="$BUNDLE"
  if [ -z "$bundle" ]; then
    bundle=/tmp/examen-update.tgz
    log "Downloading s3://$EXAMEN_BUCKET/$EXAMEN_BUNDLE_KEY"
    aws s3 cp "s3://$EXAMEN_BUCKET/$EXAMEN_BUNDLE_KEY" "$bundle" --only-show-errors
  fi
  RELEASE="$RELEASES/$(date -u +%Y%m%d%H%M%S)"
  mkdir -p "$RELEASE"
  tar -xzf "$bundle" -C "$RELEASE"
  log "Release $RELEASE ($(cat "$RELEASE/BUNDLE_SHA" 2>/dev/null || echo unknown))"
  install -m 755 "$RELEASE/bin/bee" /usr/local/bin/bee
  chown -R examen:examen "$RELEASE"
  (cd "$RELEASE" && as_examen uv venv --python 3.12 .venv -q && as_examen uv pip install -q --python .venv/bin/python -r requirements.txt)
  ln -sfn "$ENV_FILE" "$RELEASE/.env"
  install -m 755 "$RELEASE/deploy/aws/host.sh" /usr/local/sbin/examen-host
}

switch_to() {
  ln -sfn "$1" "$CURRENT.next" && mv -Tf "$CURRENT.next" "$CURRENT"
}

main() {
  exec 9>/run/lock/examen-host.lock
  flock -n 9 || { echo "Another install/update is running"; exit 0; }
  [ "$MODE" = "install" ] && prepare_host
  write_env
  local previous=""
  [ -L "$CURRENT" ] && previous="$(readlink -f "$CURRENT")"
  new_release
  install -m 644 "$RELEASE/deploy/homelab/examen.service" /etc/systemd/system/examen.service
  systemctl daemon-reload
  systemctl enable -q examen
  switch_to "$RELEASE"
  log "Restart"
  systemctl restart examen
  if healthy; then
    log "Healthy on $(cat "$RELEASE/BUNDLE_SHA" 2>/dev/null || echo unknown)"
    # Keep the three newest releases
    ls -1dt "$RELEASES"/*/ 2>/dev/null | tail -n +4 | xargs -r rm -rf
    exit 0
  fi
  log "Health check failed"
  journalctl -u examen -n 40 --no-pager || true
  if [ -n "$previous" ] && [ -d "$previous" ]; then
    log "Rolling back to $previous"
    switch_to "$previous"
    systemctl restart examen
    healthy && log "Rollback healthy"
  fi
  exit 1
}

main
